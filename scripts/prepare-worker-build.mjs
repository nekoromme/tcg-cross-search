import {execFileSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

export function assertCurrentBuild({commit,branch,remote}) {
  if(!/^[a-f0-9]{40}$/.test(commit||'')||!remote)throw new Error('公開する変更番号を確認できません');
  if(branch==='main'&&commit!==remote)throw new Error('古い変更の公開を停止しました。mainの最新変更と一致しません');
}
if(process.argv[1]===fileURLToPath(import.meta.url)) {
  const commit=process.env.WORKERS_CI_COMMIT_SHA||execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
  if(process.env.WORKERS_CI==='1') {
    const remote=execFileSync('git',['ls-remote','--exit-code','origin','refs/heads/main'],{encoding:'utf8',timeout:20000}).trim().split(/\s+/)[0];
    assertCurrentBuild({commit,branch:process.env.WORKERS_CI_BRANCH,remote});
  }
  writeFileSync(new URL('../src/build-info.js',import.meta.url),`// Generated by prepare-worker-build.mjs\nexport const BUILD_COMMIT=${JSON.stringify(commit)};\n`);
  console.log(`Worker source: ${commit}`);
}
